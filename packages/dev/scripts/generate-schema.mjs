// Regenerate src/schema.sql (PostgreSQL DDL for the sandbox) from apps/web/prisma/schema.prisma.
// Run after any Prisma schema change:  npm run schema -w @settl/dev
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const web = fileURLToPath(new URL("../../../apps/web/", import.meta.url));
const out = fileURLToPath(new URL("../src/schema.sql", import.meta.url));

const schema = readFileSync(`${web}prisma/schema.prisma`, "utf8").replace(/\r\n/g, "\n");
const hash = createHash("sha256").update(schema).digest("hex");

const npx = process.platform === "win32" ? "npx.cmd" : "npx";
const ddl = execFileSync(npx, ["prisma", "migrate", "diff", "--from-empty", "--to-schema", "prisma/schema.prisma", "--script"], {
  cwd: web,
  encoding: "utf8",
  // The diff never connects; prisma.config.ts only needs a syntactically valid URL.
  env: { ...process.env, DATABASE_URL: "postgresql://sandbox:sandbox@localhost:5432/sandbox" },
  shell: process.platform === "win32",
});

writeFileSync(out, `-- settl-schema-sha256: ${hash}\n-- Generated by scripts/generate-schema.mjs. Do not edit by hand.\n${ddl.replace(/\r\n/g, "\n")}`);
console.log(`Wrote ${out}`);
